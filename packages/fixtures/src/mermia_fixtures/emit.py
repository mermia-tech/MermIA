REPO = Path(__file__).resolve().parents[4]
SEED_SQL = Path("supabase/seed.sql")
JSON_DIR = Path("fixtures/el_guero")
SR_DIR = Path("fixtures/sr/synthetic")

# Columns whose SQL type needs an explicit cast in a VALUES list.
ARRAY_UUID = {"location_ids"}
ARRAY_TEXT = {"can_approve"}
JSONB = {"config", "stats", "payment_mix"}

# Sample exports: Centro, the last Sunday (item report) and the last week (daily report).
SAMPLE_LOCATION = "L1"
SAMPLE_ITEMS_DAY = r.LAST_DAY
SAMPLE_DAILY_FROM = dt.date(2026, 10, 5)
SAMPLE_RECIPES_DAY = r.TODAY  # the recipe book as printed that morning

# SR insumo codes and units for the Recetas export. The seed's ingredients have no code; these
# are made up. Quantities are printed in the purchase unit (the parser converts to base units),
# the prepared salsa verde in grams.
INSUMO_CODE = {i.key: f"I{n:03d}" for n, i in enumerate(r.INGREDIENTS, start=1)} | {
    r.SALSA_VERDE: "E001"
}
SR_UNIT = {"kg": "KG", "l": "LT", "pza": "PZA"}


def render() -> dict[Path, bytes]:
    """Every generated file, keyed by its path relative to the repo root."""
    data, items, days = b.build()
    files: dict[Path, bytes] = {SEED_SQL: seed_sql(data).encode()}
    for table, rows in data.items():
        files[JSON_DIR / f"{table}.json"] = dump(rows)
    files[JSON_DIR / "expected.json"] = dump(expected(items, days))
    files.update(samples(items, days))
    return files


def orphans(paths: dict[Path, bytes]) -> list[Path]:
    """Files in the generated folders that the generator no longer produces."""
    found = [p.relative_to(REPO) for d in (JSON_DIR, SR_DIR) for p in (REPO / d).glob("*")]
    return sorted(p for p in found if p not in paths)


def dump(value: Any) -> bytes:
    return (json.dumps(value, ensure_ascii=False, indent=1) + "\n").encode()


# --- SQL ---------------------------------------------------------------------------------


def literal(column: str, value: Any) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if column in JSONB:
        return quote(json.dumps(value, ensure_ascii=False, sort_keys=True)) + "::jsonb"
    if column in ARRAY_UUID:
        return quote("{" + ",".join(value) + "}") + "::uuid[]"
    if column in ARRAY_TEXT:
        return quote("{" + ",".join(value) + "}") + "::text[]"
    return quote(str(value))


def quote(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def seed_sql(data: dict[str, list[b.Row]]) -> str:
    out = [
        "-- Generated by `uv run python -m mermia_fixtures`; do not edit by hand.",
        "-- Fixture restaurant 'Taquería El Güero' (08 C7, 13 H3). Loaded by `supabase db reset`.",
        "begin;",
    ]
    for table, rows in data.items():
        columns = list(dict.fromkeys(k for row in rows for k in row))
        out.append(f"\n-- {table}: {len(rows)} rows")
        for start in range(0, len(rows), 500):
            chunk = rows[start : start + 500]
            values = ",\n".join(
                "(" + ", ".join(literal(c, row.get(c)) for c in columns) + ")" for row in chunk
            )
            out.append(f"insert into public.{table} ({', '.join(columns)}) values\n{values};")
    out.append("\ncommit;\n")
    return "\n".join(out)


# --- expected figures --------------------------------------------------------------------


def expected(items: list[b.ItemDay], days: list[b.Day]) -> dict[str, Any]:
    weekly: dict[str, dict[str, int]] = defaultdict(dict)
    for d in days:
        key = b.week_start(d.day).isoformat()
        weekly[d.location][key] = weekly[d.location].get(key, 0) + d.net_sales
    month_from = r.TODAY.replace(day=1)
    top: dict[str, list[dict[str, Any]]] = {}
    for loc in [*(lo.key for lo in r.LOCATIONS), "all"]:
        units: Counter[str] = Counter()
        for x in items:
            if month_from <= x.day <= r.LAST_DAY and loc in (x.location, "all"):
                units[x.code] += x.units
        top[loc] = [
            {"code": c, "name": b.MENU[c].name, "units": u} for c, u in units.most_common(5)
        ]
    dish_costs = []
    for m in r.MENU:
        cost = b.dish_cost(m.code, r.TODAY)
        if cost is None:
            continue
        for lo in r.LOCATIONS:
            price = b.menu_price(m.code, lo)
            net_price = price - b.vat_inside(price)
            dish_costs.append(
                {
                    "code": m.code,
                    "name": m.name,
                    "location": lo.key,
                    "cost": cost,
                    "price_gross": price,
                    "net_price": net_price,
                    "margin": net_price - cost,
                    "margin_pct": pct(net_price - cost, net_price),
                    "food_cost_pct": pct(cost, net_price),
                }
            )
    loc, sat = r.CANCEL_SATURDAY
    cancel = next(d for d in days if d.location == loc and d.day == sat)
    by_waiter = Counter(c.waiter for c in b.cancelled_tickets())
    return {
        "today": r.TODAY.isoformat(),
        "notes": [
            "Money is centavos. Sales net = gross - discount, IVA included (13 H3 quotes it so).",
            "Dish margin is on the net price (without IVA), as the MR-11 contract decides:"
            " margin_pct = (net_price - cost) / net_price, food_cost_pct = cost / net_price.",
        ],
        "weekly_net_sales": weekly,
        "daily_net_sales": {
            lo.key: {d.day.isoformat(): d.net_sales for d in days if d.location == lo.key}
            for lo in r.LOCATIONS
        },
        "top_dishes_this_month_by_units": top,
        "dish_costs_today": dish_costs,
        "cancellation_saturday": {
            "location": loc,
            "date": sat.isoformat(),
            "count": cancel.cancellations_count,
            "amount": cancel.cancellations_amount,
            "by_waiter": dict(by_waiter.most_common()),
        },
        "food_cost_yesterday": food_cost(items, r.TODAY - dt.timedelta(days=1)),
        "price_jumps": [
            {
                "ingredient": b.INGREDIENTS[k].name,
                "from_date": since.isoformat(),
                "before": f"{b.ingredient_price(k, since - dt.timedelta(days=1)):.2f}",
                "after": f"{new:.2f}",
                "unit": b.INGREDIENTS[k].unit,
            }
            for k, since, new in r.PRICE_JUMPS
        ],
    }


def pct(part: int, whole: int) -> str:
    """Percent points with one decimal, half away from zero."""
    return str((Decimal(part) * 100 / whole).quantize(Decimal("0.1"), rounding=ROUND_HALF_UP))


def food_cost(items: list[b.ItemDay], day: dt.date) -> dict[str, Any]:
    """Theoretical food cost of one day, per location (03: cost / (menu price / 1.16)).

    numerator: sum over items sold that have a recipe of units x dish cost, the dish cost in
    centavos from the recipe and the ingredient prices in effect that day (rounded once per
    dish, as dish_costs_today). denominator: the same items' net sales (gross - discount, so
    discounts lower it) less the IVA inside them. pct = numerator / denominator.
    coverage_pct = those items' net / the day's whole net (both with IVA; the ratio is the
    same without). Items with no recipe count in neither the numerator nor the denominator.
    """
    out: dict[str, Any] = {"date": day.isoformat(), "definition": food_cost.__doc__}
    for lo in r.LOCATIONS:
        rows = [x for x in items if x.location == lo.key and x.day == day]
        covered = [x for x in rows if b.dish_cost(x.code, day) is not None]
        cost = sum(x.units * (b.dish_cost(x.code, day) or 0) for x in covered)
        net = sum(x.net for x in covered)
        net_ex_vat = net - b.vat_inside(net)
        out[lo.key] = {
            "numerator_cost": cost,
            "denominator_net_ex_iva": net_ex_vat,
            "covered_net": net,
            "day_net": sum(x.net for x in rows),
            "pct": pct(cost, net_ex_vat),
            "coverage_pct": pct(net, sum(x.net for x in rows)),
            "items": [
                {
                    "code": x.code,
                    "units": x.units,
                    "dish_cost": b.dish_cost(x.code, day),
                    "cost": x.units * (b.dish_cost(x.code, day) or 0),
                    "net": x.net,
                }
                for x in covered
            ],
        }
    return out


# --- sample SR exports -------------------------------------------------------------------


def pesos(centavos: int) -> float:
    """Excel stores numbers as floats; two decimals are exact enough for a display copy."""
    return round(centavos / 100, 2)


def location(key: str) -> r.Location:
    return next(lo for lo in r.LOCATIONS if lo.key == key)


def samples(items: list[b.ItemDay], days: list[b.Day]) -> dict[Path, bytes]:
    lo = location(SAMPLE_LOCATION)
    sold = [x for x in items if x.location == lo.key and x.day == SAMPLE_ITEMS_DAY and x.units > 0]
    week = [
        d
        for d in days
        if d.location == lo.key
        and SAMPLE_DAILY_FROM <= d.day <= SAMPLE_DAILY_FROM + dt.timedelta(days=6)
    ]
    stem_i = f"productos_vendidos_{lo.key}_{SAMPLE_ITEMS_DAY.isoformat()}"
    stem_d = f"ventas_por_dia_{lo.key}_{SAMPLE_DAILY_FROM.isoformat()}"
    stem_r = f"recetas_{lo.key}_{SAMPLE_RECIPES_DAY.isoformat()}"
    return {
        SR_DIR / f"{stem_i}.xlsx": items_xlsx(lo, sold),
        SR_DIR / f"{stem_i}.golden.json": golden(items_golden(lo, sold)),
        SR_DIR / f"{stem_d}.xlsx": daily_xlsx(lo, week, items),
        SR_DIR / f"{stem_d}.golden.json": golden(daily_golden(lo, week)),
        SR_DIR / f"{stem_r}.xlsx": recipes_xlsx(lo),
        SR_DIR / f"{stem_r}.golden.json": golden(recipes_golden(lo)),
    }


def golden(batch: dict[str, Any]) -> bytes:
    """Writes a golden batch through the contract, so a contract change fails here first."""
    model = NormalizedBatch.model_validate_json(json.dumps(batch))
    return dump(model.model_dump(mode="json"))


