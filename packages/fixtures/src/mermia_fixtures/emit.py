@dataclass(frozen=True)
class RecipeLine:
    """One line of a dish recipe: ingredient key and quantity in its base unit."""

    key: str
    qty: Decimal

    @property
    def is_prepared(self) -> bool:
        return self.key == r.SALSA_VERDE

    @property
    def name(self) -> str:
        return r.SALSA_VERDE_NAME if self.is_prepared else b.INGREDIENTS[self.key].name

    @property
    def base_unit(self) -> str:
        return "g" if self.is_prepared else b.INGREDIENTS[self.key].base_unit

    @property
    def yield_pct(self) -> Decimal | None:
        """None for the prepared salsa: its loss is in its own recipe's yield."""
        return None if self.is_prepared else b.INGREDIENTS[self.key].yield_pct

    def as_printed(self) -> tuple[Decimal, str]:
        """Quantity and unit as the export shows them: purchase unit, salsa in grams."""
        if self.is_prepared:
            return self.qty, "GR"
        ing = b.INGREDIENTS[self.key]
        return self.qty * ing.per_base, SR_UNIT[ing.unit]


def recipe_lines(m: r.MenuItem) -> list[RecipeLine]:
    return [RecipeLine(k, Decimal(q)) for k, q in m.recipe]


def recipes_golden(lo: r.Location) -> dict[str, Any]:
    day = SAMPLE_RECIPES_DAY.isoformat()
    recipes = [m for m in r.MENU if m.recipe]
    return {
        "contract_version": 1,
        "parser": b.PARSER_RECIPES,
        "source_kind": "sr_report",
        "quality": "file",
        "location_hint": lo.name,
        "period": {"from": day, "to": day},
        "grain": "catalog",
        "totals": {"lines": len(recipes)},
        "recipes": [
            {
                "menu_item_external_id": m.code,
                "menu_item_name": m.name,
                "yield_qty": "1.000000",
                "lines": [
                    {
                        "ingredient_name": x.name,
                        "ingredient_external_id": INSUMO_CODE[x.key],
                        "qty_base": f"{x.qty:.6f}",
                        "unit": x.base_unit,
                        "yield_override_pct": (
                            None if x.yield_pct is None else f"{x.yield_pct:.4f}"
                        ),
                    }
                    for x in recipe_lines(m)
                ],
            }
            for m in recipes
        ],
    }


def recipes_xlsx(lo: r.Location) -> bytes:
    """One row per recipe line. Costo is the line's cost that day in pesos; the parser reads
    past it (the contract has no field for it)."""
    wb = Workbook()
    ws = wb.active
    assert ws is not None
    ws.title = "Recetas"
    ws.append([f"{r.TENANT_NAME} - {lo.name}"])
    ws.append(["Recetas - Productos"])
    ws.append([f"Al {SAMPLE_RECIPES_DAY:%d/%m/%Y}"])
    ws.append([])
    ws.append(
        [
            "Clave",
            "Producto",
            "Clave insumo",
            "Insumo",
            "Cantidad",
            "Unidad",
            "Rendimiento %",
            "Costo",
        ]
    )
    for m in r.MENU:
        for x in recipe_lines(m):
            qty, unit = x.as_printed()
            cost = b.line_cost(x.key, x.qty, SAMPLE_RECIPES_DAY)
            ws.append(
                [
                    m.code,
                    m.name,
                    INSUMO_CODE[x.key],
                    x.name,
                    float(qty),
                    unit,
                    None if x.yield_pct is None else float(x.yield_pct),
                    float(cost.quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)),
                ]
            )
    return save(wb)


def header(ws: Any, lo: r.Location, title: str, first: dt.date, last: dt.date) -> None:
    ws.append([f"{r.TENANT_NAME} - {lo.name}"])
    ws.append([title])
    ws.append([f"Del {first:%d/%m/%Y} al {last:%d/%m/%Y}"])
    ws.append([])


def items_xlsx(lo: r.Location, sold: list[b.ItemDay]) -> bytes:
    wb = Workbook()
    ws = wb.active
    assert ws is not None
    ws.title = "Productos vendidos"
    header(ws, lo, "Productos vendidos en general", SAMPLE_ITEMS_DAY, SAMPLE_ITEMS_DAY)
    ws.append(
        ["Clave", "Descripción", "Grupo", "Cantidad", "Precio", "Importe", "Descuento", "Total"]
    )
    for x in sold:
        ws.append(
            [
                x.code,
                b.MENU[x.code].name,
                b.MENU[x.code].category,
                x.units,
                pesos(x.gross // x.units),
                pesos(x.gross),
                pesos(x.discount),
                pesos(x.net),
            ]
        )
    ws.append(
        [
            "",
            "Total",
            "",
            sum(x.units for x in sold),
            None,
            pesos(sum(x.gross for x in sold)),
            pesos(sum(x.discount for x in sold)),
            pesos(sum(x.net for x in sold)),
        ]
    )
    return save(wb)


def daily_xlsx(lo: r.Location, week: list[b.Day], items: list[b.ItemDay]) -> bytes:
    wb = Workbook()
    ws = wb.active
    assert ws is not None
    ws.title = "Ventas por día"
    header(ws, lo, "Ventas por día", week[0].day, week[-1].day)
    ws.append(
        [
            "Fecha",
            "Cuentas",
            "Personas",
            "Alimentos",
            "Bebidas",
            "Descuentos",
            "Venta neta",
            "IVA",
            "Propinas",
            "Efectivo",
            "Tarjeta",
            "Transferencia",
            "Cancelaciones",
            "Importe cancelado",
        ]
    )
    for d in week:
        day_items = [x for x in items if x.location == lo.key and x.day == d.day]
        drinks = sum(x.gross for x in day_items if b.MENU[x.code].category == "Bebidas")
        food = sum(x.gross for x in day_items) - drinks
        ws.append(
            [
                d.day.strftime("%d/%m/%Y"),
                d.tickets,
                d.guests,
                pesos(food),
                pesos(drinks),
                pesos(d.discounts),
                pesos(d.net_sales),
                pesos(d.tax),
                pesos(d.tips),
                pesos(d.payment_mix["cash"]),
                pesos(d.payment_mix["card"]),
                pesos(d.payment_mix["transfer"]),
                d.cancellations_count,
                pesos(d.cancellations_amount),
            ]
        )
    return save(wb)


FIXED_TIME = dt.datetime(2026, 10, 12, 9, 0, 0)


def save(wb: Workbook) -> bytes:
    """Saves with fixed timestamps so regenerating gives the same bytes."""
    wb.properties.creator = "MermIA fixtures"
    wb.properties.created = FIXED_TIME
    wb.properties.modified = FIXED_TIME
    raw = io.BytesIO()
    wb.save(raw)
    out = io.BytesIO()
    with zipfile.ZipFile(raw) as src, zipfile.ZipFile(out, "w", zipfile.ZIP_STORED) as dst:
        for info in src.infolist():
            fixed = zipfile.ZipInfo(info.filename, date_time=(1980, 1, 1, 0, 0, 0))
            # stored, not deflated: deflate output varies with the zlib build
            fixed.compress_type = zipfile.ZIP_STORED
            content = src.read(info.filename)
            if info.filename == "docProps/core.xml":
                # openpyxl stamps "modified" with the current time on save.
                content = re.sub(
                    rb"(<dcterms:modified[^>]*>)[^<]*", rb"\g<1>2026-10-12T09:00:00Z", content
                )
            dst.writestr(fixed, content)
    return out.getvalue()
