def expected(items: list[b.ItemDay], days: list[b.Day]) -> dict[str, Any]:
    weekly: dict[str, dict[str, int]] = defaultdict(dict)
    for d in days:
        key = b.week_start(d.day).isoformat()
        weekly[d.location][key] = weekly[d.location].get(key, 0) + d.net_sales
    month_from = r.TODAY.replace(day=1)
    top: dict[str, list[dict[str, Any]]] = {}
    for loc in [*(lo.key for lo in r.LOCATIONS), "all"]:
        units: Counter[str] = Counter()
        for x in items:
            if month_from <= x.day <= r.LAST_DAY and loc in (x.location, "all"):
                units[x.code] += x.units
        top[loc] = [
            {"code": c, "name": b.MENU[c].name, "units": u} for c, u in units.most_common(5)
        ]
    dish_costs = []
    for m in r.MENU:
        cost = b.dish_cost(m.code, r.TODAY)
        if cost is None:
            continue
        for lo in r.LOCATIONS:
            price = b.menu_price(m.code, lo)
            dish_costs.append(
                {
                    "code": m.code,
                    "name": m.name,
                    "location": lo.key,
                    "cost": cost,
                    "price_gross": price,
                    "margin_pct_of_gross": str(
                        (Decimal(price - cost) * 100 / price).quantize(Decimal("0.1"))
                    ),
                }
            )
    loc, sat = r.CANCEL_SATURDAY
    cancel = next(d for d in days if d.location == loc and d.day == sat)
    by_waiter = Counter(c.waiter for c in b.cancelled_tickets())
    return {
        "today": r.TODAY.isoformat(),
        "notes": [
            "Money is centavos. Sales net = gross - discount, IVA included (13 H3 quotes it so).",
            "margin_pct_of_gross = (price_gross - cost) / price_gross, as 13 H3 example 4.",
        ],
        "weekly_net_sales": weekly,
        "daily_net_sales": {
            lo.key: {d.day.isoformat(): d.net_sales for d in days if d.location == lo.key}
            for lo in r.LOCATIONS
        },
        "top_dishes_this_month_by_units": top,
        "dish_costs_today": dish_costs,
        "cancellation_saturday": {
            "location": loc,
            "date": sat.isoformat(),
            "count": cancel.cancellations_count,
            "amount": cancel.cancellations_amount,
            "by_waiter": dict(by_waiter.most_common()),
        },
        "food_cost_yesterday": food_cost(items, r.TODAY - dt.timedelta(days=1)),
        "price_jumps": [
            {
                "ingredient": b.INGREDIENTS[k].name,
                "from_date": since.isoformat(),
                "before": f"{b.ingredient_price(k, since - dt.timedelta(days=1)):.2f}",
                "after": f"{new:.2f}",
                "unit": b.INGREDIENTS[k].unit,
            }
            for k, since, new in r.PRICE_JUMPS
        ],
    }


def food_cost(items: list[b.ItemDay], day: dt.date) -> dict[str, Any]:
    """Theoretical food cost of one day, per location.

    pct = recipe cost of the items sold / their net sales without IVA, over the items that
    have a recipe; coverage_pct = that net / the day's whole net. Both in percent points.
    """
    out: dict[str, Any] = {"date": day.isoformat(), "definition": food_cost.__doc__}
    for lo in r.LOCATIONS:
        rows = [x for x in items if x.location == lo.key and x.day == day]
        covered = [x for x in rows if b.dish_cost(x.code, day) is not None]
        cost = sum(x.units * (b.dish_cost(x.code, day) or 0) for x in covered)
        net = sum(x.net for x in covered)
        net_ex_vat = net - b.vat_inside(net)
        out[lo.key] = {
            "cost": cost,
            "covered_net_ex_iva": net_ex_vat,
            "pct": str((Decimal(cost) * 100 / net_ex_vat).quantize(Decimal("0.1"))),
            "coverage_pct": str(
                (Decimal(net) * 100 / sum(x.net for x in rows)).quantize(Decimal("0.1"))
            ),
        }
    return out


# --- sample SR exports -------------------------------------------------------------------


def pesos(centavos: int) -> float:
    """Excel stores numbers as floats; two decimals are exact enough for a display copy."""
    return round(centavos / 100, 2)


def location(key: str) -> r.Location:
    return next(lo for lo in r.LOCATIONS if lo.key == key)


def samples(items: list[b.ItemDay], days: list[b.Day]) -> dict[Path, bytes]:
    lo = location(SAMPLE_LOCATION)
    sold = [x for x in items if x.location == lo.key and x.day == SAMPLE_ITEMS_DAY and x.units > 0]
    week = [
        d
        for d in days
        if d.location == lo.key
        and SAMPLE_DAILY_FROM <= d.day <= SAMPLE_DAILY_FROM + dt.timedelta(days=6)
    ]
    stem_i = f"productos_vendidos_{lo.key}_{SAMPLE_ITEMS_DAY.isoformat()}"
    stem_d = f"ventas_por_dia_{lo.key}_{SAMPLE_DAILY_FROM.isoformat()}"
    return {
        SR_DIR / f"{stem_i}.xlsx": items_xlsx(lo, sold),
        SR_DIR / f"{stem_i}.golden.json": golden(items_golden(lo, sold)),
        SR_DIR / f"{stem_d}.xlsx": daily_xlsx(lo, week, items),
        SR_DIR / f"{stem_d}.golden.json": golden(daily_golden(lo, week)),
    }


def golden(batch: dict[str, Any]) -> bytes:
    """Writes a golden batch through the contract, so a contract change fails here first."""
    model = NormalizedBatch.model_validate_json(json.dumps(batch))
    return dump(model.model_dump(mode="json"))


def items_golden(lo: r.Location, sold: list[b.ItemDay]) -> dict[str, Any]:
    day = SAMPLE_ITEMS_DAY.isoformat()
    return {
        "contract_version": 1,
        "parser": b.PARSER_ITEMS,
        "source_kind": "sr_report",
        "quality": "file",
        "location_hint": lo.name,
        "period": {"from": day, "to": day},
        "grain": "item_daily",
        "totals": {
            "net_sales": sum(x.net for x in sold),
            "units": f"{sum(x.units for x in sold)}.000000",
            "lines": len(sold),
        },
        "menu_items": [
            {
                "external_id": x.code,
                "name": b.MENU[x.code].name,
                "category": b.MENU[x.code].category,
                "kind": b.MENU[x.code].kind,
            }
            for x in sold
        ],
        "item_sales": [
            {
                "item_external_id": x.code,
                "item_name": b.MENU[x.code].name,
                "period_from": day,
                "period_to": day,
                "units": f"{x.units}.000000",
                "gross": x.gross,
                "discount": x.discount,
                "net": x.net,
            }
            for x in sold
        ],
    }


def daily_golden(lo: r.Location, week: list[b.Day]) -> dict[str, Any]:
    return {
        "contract_version": 1,
        "parser": b.PARSER_DAILY,
        "source_kind": "sr_report",
        "quality": "file",
        "location_hint": lo.name,
        "period": {"from": week[0].day.isoformat(), "to": week[-1].day.isoformat()},
        "grain": "daily",
        "totals": {"net_sales": sum(d.net_sales for d in week), "lines": len(week)},
        "daily_sales": [
            {
                "business_date": d.day.isoformat(),
                "net_sales": d.net_sales,
                "tax": d.tax,
                "tickets": d.tickets,
                "guests": d.guests,
                "discounts": d.discounts,
                "cancellations_amount": d.cancellations_amount,
                "cancellations_count": d.cancellations_count,
                "payment_mix": d.payment_mix,
                "tips": d.tips,
            }
            for d in week
        ],
    }


def header(ws: Any, lo: r.Location, title: str, first: dt.date, last: dt.date) -> None:
    ws.append([f"{r.TENANT_NAME} - {lo.name}"])
    ws.append([title])
    ws.append([f"Del {first:%d/%m/%Y} al {last:%d/%m/%Y}"])
    ws.append([])


def items_xlsx(lo: r.Location, sold: list[b.ItemDay]) -> bytes:
    wb = Workbook()
    ws = wb.active
    assert ws is not None
    ws.title = "Productos vendidos"
    header(ws, lo, "Productos vendidos en general", SAMPLE_ITEMS_DAY, SAMPLE_ITEMS_DAY)
    ws.append(
        ["Clave", "Descripción", "Grupo", "Cantidad", "Precio", "Importe", "Descuento", "Total"]
    )
    for x in sold:
        ws.append(
            [
                x.code,
                b.MENU[x.code].name,
                b.MENU[x.code].category,
                x.units,
                pesos(x.gross // x.units),
                pesos(x.gross),
                pesos(x.discount),
                pesos(x.net),
            ]
        )
    ws.append(
        [
            "",
            "Total",
            "",
            sum(x.units for x in sold),
            None,
            pesos(sum(x.gross for x in sold)),
            pesos(sum(x.discount for x in sold)),
            pesos(sum(x.net for x in sold)),
        ]
    )
    return save(wb)


def daily_xlsx(lo: r.Location, week: list[b.Day], items: list[b.ItemDay]) -> bytes:
    wb = Workbook()
    ws = wb.active
    assert ws is not None
    ws.title = "Ventas por día"
    header(ws, lo, "Ventas por día", week[0].day, week[-1].day)
    ws.append(
        [
            "Fecha",
            "Cuentas",
            "Personas",
            "Alimentos",
            "Bebidas",
            "Descuentos",
            "Venta neta",
            "IVA",
            "Propinas",
            "Efectivo",
            "Tarjeta",
            "Transferencia",
            "Cancelaciones",
            "Importe cancelado",
        ]
    )
    for d in week:
        day_items = [x for x in items if x.location == lo.key and x.day == d.day]
        drinks = sum(x.gross for x in day_items if b.MENU[x.code].category == "Bebidas")
        food = sum(x.gross for x in day_items) - drinks
        ws.append(
            [
                d.day.strftime("%d/%m/%Y"),
                d.tickets,
                d.guests,
                pesos(food),
                pesos(drinks),
                pesos(d.discounts),
                pesos(d.net_sales),
                pesos(d.tax),
                pesos(d.tips),
                pesos(d.payment_mix["cash"]),
                pesos(d.payment_mix["card"]),
                pesos(d.payment_mix["transfer"]),
                d.cancellations_count,
                pesos(d.cancellations_amount),
            ]
        )
    return save(wb)


FIXED_TIME = dt.datetime(2026, 10, 12, 9, 0, 0)


def save(wb: Workbook) -> bytes:
    """Saves with fixed timestamps so regenerating gives the same bytes."""
    wb.properties.creator = "MermIA fixtures"
    wb.properties.created = FIXED_TIME
    wb.properties.modified = FIXED_TIME
    raw = io.BytesIO()
    wb.save(raw)
    out = io.BytesIO()
    with zipfile.ZipFile(raw) as src, zipfile.ZipFile(out, "w", zipfile.ZIP_STORED) as dst:
        for info in src.infolist():
            fixed = zipfile.ZipInfo(info.filename, date_time=(1980, 1, 1, 0, 0, 0))
            # stored, not deflated: deflate output varies with the zlib build
            fixed.compress_type = zipfile.ZIP_STORED
            content = src.read(info.filename)
            if info.filename == "docProps/core.xml":
                # openpyxl stamps "modified" with the current time on save.
                content = re.sub(
                    rb"(<dcterms:modified[^>]*>)[^<]*", rb"\g<1>2026-10-12T09:00:00Z", content
                )
            dst.writestr(fixed, content)
    return out.getvalue()
